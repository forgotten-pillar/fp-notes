#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises"
import { existsSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { dirname, join, resolve } from "node:path"
import sharp from "sharp"

const SVG_URL = "https://forgotten-pillar.s3.us-east-2.amazonaws.com/fp-notes-logo.svg"
const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = resolve(__dirname, "..")
const OUT_DIR = join(ROOT, "quartz", "static", "icons")

const THEME = "#106a8f"
const BG_WHITE = { r: 255, g: 255, b: 255, alpha: 1 }
const TRANSPARENT = { r: 0, g: 0, b: 0, alpha: 0 }

async function fetchSvg() {
  const res = await fetch(SVG_URL)
  if (!res.ok) throw new Error(`Failed to fetch SVG: ${res.status} ${res.statusText}`)
  return Buffer.from(await res.arrayBuffer())
}

async function renderToCanvas({ svg, size, contentScale, background }) {
  const contentSize = Math.round(size * contentScale)
  const rendered = await sharp(svg, { density: 384 })
    .resize(contentSize, contentSize, { fit: "contain", background: TRANSPARENT })
    .png()
    .toBuffer()
  const offset = Math.round((size - contentSize) / 2)
  return sharp({
    create: { width: size, height: size, channels: 4, background },
  })
    .composite([{ input: rendered, top: offset, left: offset }])
    .png()
}

async function renderMonochromeBadge({ svg, size }) {
  const contentSize = Math.round(size * 0.85)
  const rendered = await sharp(svg, { density: 256 })
    .resize(contentSize, contentSize, { fit: "contain", background: TRANSPARENT })
    .threshold(128, { greyscale: true })
    .toBuffer()
  const flat = await sharp(rendered)
    .ensureAlpha()
    .extractChannel("alpha")
    .toColourspace("b-w")
    .toBuffer()
  const tinted = await sharp({
    create: { width: contentSize, height: contentSize, channels: 4, background: TRANSPARENT },
  })
    .composite([
      {
        input: await sharp({
          create: {
            width: contentSize,
            height: contentSize,
            channels: 4,
            background: { r: 255, g: 255, b: 255, alpha: 1 },
          },
        })
          .png()
          .toBuffer(),
        blend: "dest-in",
        input_alpha: flat,
      },
    ])
    .png()
    .toBuffer()
  const offset = Math.round((size - contentSize) / 2)
  return sharp({
    create: { width: size, height: size, channels: 4, background: TRANSPARENT },
  })
    .composite([{ input: tinted, top: offset, left: offset }])
    .png()
}

async function writeIcon(name, image) {
  const outPath = join(OUT_DIR, name)
  await image.toFile(outPath)
  console.log(`  wrote ${outPath}`)
}

async function main() {
  if (!existsSync(OUT_DIR)) await mkdir(OUT_DIR, { recursive: true })
  console.log(`Downloading SVG from ${SVG_URL}`)
  const svg = await fetchSvg()

  console.log("Generating icons …")
  await writeIcon(
    "icon-192.png",
    await renderToCanvas({ svg, size: 192, contentScale: 1.0, background: BG_WHITE }),
  )
  await writeIcon(
    "icon-512.png",
    await renderToCanvas({ svg, size: 512, contentScale: 1.0, background: BG_WHITE }),
  )
  await writeIcon(
    "icon-512-maskable.png",
    await renderToCanvas({ svg, size: 512, contentScale: 0.8, background: BG_WHITE }),
  )
  await writeIcon(
    "apple-touch-icon.png",
    await renderToCanvas({ svg, size: 180, contentScale: 1.0, background: BG_WHITE }),
  )

  const badgeSize = 72
  const badgeContent = Math.round(badgeSize * 0.85)
  const badgeMask = await sharp(svg, { density: 256 })
    .resize(badgeContent, badgeContent, { fit: "contain", background: TRANSPARENT })
    .ensureAlpha()
    .extractChannel("alpha")
    .toBuffer()
  const badgeFilled = await sharp({
    create: {
      width: badgeContent,
      height: badgeContent,
      channels: 4,
      background: { r: 255, g: 255, b: 255, alpha: 1 },
    },
  })
    .joinChannel(badgeMask)
    .png()
    .toBuffer()
  const offset = Math.round((badgeSize - badgeContent) / 2)
  await writeIcon(
    "badge-72.png",
    sharp({
      create: { width: badgeSize, height: badgeSize, channels: 4, background: TRANSPARENT },
    })
      .composite([{ input: badgeFilled, top: offset, left: offset }])
      .png(),
  )

  await writeFile(
    join(OUT_DIR, ".gitkeep"),
    "# Icons in this folder are generated by scripts/generate-pwa-icons.mjs\n",
  )

  console.log(`\nDone. Theme color: ${THEME}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
